// Geometry smoke test that uses RmlUi's real layout engine, not a browser.
// It catches the narrow/overlapped binding rows reported on Windows.
#include <RmlUi/Core.h>
#include <RmlUi/Core/Context.h>
#include <RmlUi/Core/Element.h>
#include <RmlUi/Core/ElementDocument.h>
#include <RmlUi/Core/RenderInterface.h>

#include <cstdio>
#include <string>

class NullRenderer final : public Rml::RenderInterface {
public:
    Rml::CompiledGeometryHandle CompileGeometry(Rml::Span<const Rml::Vertex>,
                                                 Rml::Span<const int>) override { return 1; }
    void RenderGeometry(Rml::CompiledGeometryHandle, Rml::Vector2f, Rml::TextureHandle) override {}
    void ReleaseGeometry(Rml::CompiledGeometryHandle) override {}
    Rml::TextureHandle LoadTexture(Rml::Vector2i& size, const Rml::String&) override {
        size = {1, 1};
        return 1;
    }
    Rml::TextureHandle GenerateTexture(Rml::Span<const Rml::byte>, Rml::Vector2i) override {
        return 1;
    }
    void ReleaseTexture(Rml::TextureHandle) override {}
    void EnableScissorRegion(bool) override {}
    void SetScissorRegion(Rml::Rectanglei) override {}
};

int main(int argc, char** argv) {
    if (argc != 2) {
        std::fprintf(stderr, "Usage: knomira_rmlui_layout_test <game_shell.rml>\n");
        return 1;
    }

    NullRenderer renderer;
    Rml::SetRenderInterface(&renderer);
    if (!Rml::Initialise()) {
        std::fprintf(stderr, "Could not initialize RmlUi core\n");
        return 2;
    }

#ifdef _WIN32
    if (!Rml::LoadFontFace("C:/Windows/Fonts/segoeui.ttf") &&
        !Rml::LoadFontFace("C:/Windows/Fonts/arial.ttf")) {
        std::fprintf(stderr, "Could not load a Windows UI font\n");
        Rml::Shutdown();
        return 3;
    }
#endif
    int status = 0;
    {
        Rml::Context* context = Rml::CreateContext("knomira-layout-smoke", {1280, 800});
        Rml::ElementDocument* doc = context ? context->LoadDocument(argv[1]) : nullptr;
        if (!doc) {
            std::fprintf(stderr, "Could not load Knomira controls document\n");
            status = 4;
        } else {
            auto* settings = doc->GetElementById("settings_panel");
            auto* menu = doc->GetElementById("menu_panel");
            auto* list = doc->GetElementById("bindings_list");
            if (!settings || !menu || !list) {
                std::fprintf(stderr, "Controls screen missing required elements\n");
                status = 5;
            } else {
                menu->SetProperty("display", "none");
                settings->SetProperty("display", "block");

                // Representative markup generated by QtMenuWindow::RebuildSettings().
                // Use distinct IDs so the actual box geometry can be validated.
                list->SetInnerRML(
                    "<div id='test_row' class='binding-row'>"
                      "<div id='test_info' class='binding-info'>"
                        "<p class='binding-name'>Previous menu item</p>"
                        "<p class='binding-detail'>ACTIVE IN MENU</p>"
                      "</div>"
                      "<div id='test_primary' class='binding-slot'>"
                        "<p id='test_primary_value' class='binding-value'>D-pad Up</p>"
                        "<button id='test_primary_button' class='bind-button'>Change</button>"
                      "</div>"
                      "<div id='test_alternate' class='binding-slot'>"
                        "<p class='binding-value'>Left stick Up</p>"
                        "<button id='test_alternate_button' class='bind-button'>Change</button>"
                      "</div>"
                    "</div>");
                doc->Show();
                context->Update();

                auto element = [doc](const char* id) { return doc->GetElementById(id); };
                auto left = [](Rml::Element* e) {
                    return e->GetAbsoluteOffset(Rml::BoxArea::Border).x;
                };
                auto right = [&](Rml::Element* e) {
                    return left(e) + e->GetOffsetWidth();
                };
                auto checkSize = [&](const char* id, float minWidth) {
                    auto* e = element(id);
                    const float width = e ? e->GetOffsetWidth() : 0.f;
                    std::printf("%s: %.1f px\n", id, width);
                    if (width < minWidth) {
                        std::fprintf(stderr, "%s is collapsed (wanted at least %.0f px)\n", id, minWidth);
                        status = 6;
                    }
                };
                checkSize("bindings_list", 950.f);
                checkSize("test_row", 900.f);
                checkSize("test_info", 270.f);
                checkSize("test_primary", 270.f);
                checkSize("test_alternate", 270.f);
                checkSize("test_primary_value", 170.f);
                checkSize("test_primary_button", 85.f);
                checkSize("test_alternate_button", 85.f);

                if (auto* info = element("test_info")) {
                    auto* primary = element("test_primary");
                    auto* alternate = element("test_alternate");
                    if (!primary || !alternate ||
                        left(primary) + 1.f < right(info) ||
                        left(alternate) + 1.f < right(primary)) {
                        std::fprintf(stderr, "Action, Primary and Alternate columns overlap\n");
                        status = 7;
                    }
                }
                auto* hint = element("settings_hint");
                auto* label = doc->GetElementById("settings_hint") ? element("settings_hint") : nullptr;
                auto* category = element("controls_tab_menu");
                if (hint && label && category &&
                    category->GetAbsoluteOffset(Rml::BoxArea::Border).y <
                    hint->GetAbsoluteOffset(Rml::BoxArea::Border).y + hint->GetOffsetHeight() - 1.f) {
                    std::fprintf(stderr, "Category controls overlap the help text\n");
                    status = 8;
                }
            }
        }
    }
    Rml::Shutdown();
    if (status == 0) std::puts("PASS: visible binding table has non-overlapping full-width columns.");
    return status;
}
